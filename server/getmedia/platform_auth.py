"""平台授权（P2e）：Cookie 的导入、加密保存与绑定状态。

三条硬约束：
1. Cookie 明文**只**以两种形式存在：请求体内存、服务端 600 权限的 Netscape 文件；
   数据库里存的是 ``CredentialVault.seal()`` 的密文，接口从不回显明文。
2. 抖音开放平台 OAuth（C 方案）在未配置 ``client_key``/回调时保持禁用，回调接口返回 501。
3. 解绑只删绑定与凭据文件，不动任何媒体数据。
"""
from __future__ import annotations

import logging
import os
import re
import uuid
from pathlib import Path

from sqlalchemy import text
from sqlalchemy.engine import Engine

from .config import Settings
from .credentials import CredentialError, CredentialVault

log = logging.getLogger("getmedia.platform_auth")

PLATFORMS = {
    "bilibili": {"name": "哔哩哔哩", "methods": ["webview", "cookie"], "hint": "需要 SESSDATA 等登录 Cookie"},
    "douyin": {"name": "抖音", "methods": ["webview", "cookie"], "hint": "需要 sessionid / ttwid 等登录 Cookie"},
}
SESSION_TTL = 600
MAX_COOKIE = 16 * 1024
_PAIR = re.compile(r"^[A-Za-z0-9_\-\.]+=[^;]*$")


class AuthError(Exception):
    def __init__(self, code: str, detail: str, status: int = 400):
        super().__init__(detail)
        self.code, self.detail, self.status = code, detail, status


def parse_cookie_text(raw: str) -> dict[str, str]:
    """解析 ``a=1; b=2`` 或浏览器导出的多行形式；只保留合法键值对。"""
    text_ = (raw or "").strip()
    if not text_:
        raise AuthError("empty_cookie", "Cookie 不能为空")
    if len(text_) > MAX_COOKIE:
        raise AuthError("cookie_too_large", f"Cookie 不能超过 {MAX_COOKIE // 1024} KB")
    jar: dict[str, str] = {}
    for part in re.split(r"[;\n\r]+", text_):
        piece = part.strip()
        if not piece:
            continue
        if "\t" in piece:  # Netscape 导出的行：domain  flag  path  secure  expiry  name  value
            cols = piece.split("\t")
            if len(cols) >= 7 and cols[5]:
                jar[cols[5]] = cols[6]
            continue
        if _PAIR.match(piece):
            k, _, v = piece.partition("=")
            jar[k.strip()] = v.strip()
    if not jar:
        raise AuthError("cookie_unparsable", "没有解析出任何 Cookie 键值对，请检查复制内容")
    return jar


def netscape(jar: dict[str, str], platform: str) -> str:
    domain = ".bilibili.com" if platform == "bilibili" else ".douyin.com"
    lines = ["# Netscape HTTP Cookie File", "# generated by getmedia platform-auth"]
    for k, v in jar.items():
        lines.append(f"{domain}\tTRUE\t/\tTRUE\t0\t{k}\t{v}")
    return "\n".join(lines) + "\n"


class PlatformAuthService:
    def __init__(self, engine: Engine, settings: Settings, clock, vault: CredentialVault):
        self.engine, self.s, self.clock, self.vault = engine, settings, clock, vault

    def now(self) -> int:
        return int(self.clock())

    # ---------- 平台与绑定 ----------
    @staticmethod
    def platforms() -> list[dict]:
        return [{"platform": k, "name": v["name"], "methods": v["methods"], "hint": v["hint"],
                 "oauth": "unconfigured"} for k, v in PLATFORMS.items()]

    def bindings(self, user_id: str) -> list[dict]:
        with self.engine.begin() as c:
            rows = c.execute(text(
                "SELECT b.platform, b.bound_at, b.source, b.status, p.label, p.updated_at"
                " FROM account_platform_bindings b LEFT JOIN platform_credentials p"
                " ON p.user_id=b.user_id AND p.platform=b.platform WHERE b.user_id=:u"),
                {"u": user_id}).all()
        return [dict(r._mapping) for r in rows]

    # ---------- 授权会话 ----------
    def start(self, user_id: str, platform: str, method: str = "webview") -> dict:
        if platform not in PLATFORMS:
            raise AuthError("unknown_platform", f"不支持的平台：{platform}")
        if method not in PLATFORMS[platform]["methods"]:
            raise AuthError("unknown_method", f"{platform} 不支持该授权方式")
        sid, now = "as_" + uuid.uuid4().hex[:20], self.now()
        with self.engine.begin() as c:
            c.execute(text("INSERT INTO platform_auth_sessions(id, user_id, platform, method, status,"
                           " created_at, expires_at) VALUES(:i,:u,:p,:m,'pending',:n,:e)"),
                      {"i": sid, "u": user_id, "p": platform, "m": method, "n": now, "e": now + SESSION_TTL})
        return {"session_id": sid, "platform": platform, "method": method, "status": "pending",
                "expires_at": now + SESSION_TTL}

    def _session(self, user_id: str, sid: str) -> dict:
        with self.engine.begin() as c:
            row = c.execute(text("SELECT id, user_id, platform, method, status, message, created_at, expires_at"
                                 " FROM platform_auth_sessions WHERE id=:i AND user_id=:u"),
                            {"i": sid, "u": user_id}).first()
        if row is None:
            raise AuthError("session_not_found", "授权会话不存在，请重新发起", 404)
        return dict(row._mapping)

    def status(self, user_id: str, sid: str) -> dict:
        s = self._session(user_id, sid)
        expired = s["expires_at"] < self.now() and s["status"] == "pending"
        return {"session_id": s["id"], "platform": s["platform"], "method": s["method"],
                "status": "expired" if expired else s["status"], "message": s["message"],
                "expires_at": s["expires_at"]}

    def cancel(self, user_id: str, sid: str) -> dict:
        self._session(user_id, sid)
        with self.engine.begin() as c:
            c.execute(text("UPDATE platform_auth_sessions SET status='cancelled' WHERE id=:i AND user_id=:u"),
                      {"i": sid, "u": user_id})
        return {"session_id": sid, "status": "cancelled"}

    def complete_cookie(self, user_id: str, sid: str, cookie_text: str) -> dict:
        s = self._session(user_id, sid)
        if s["status"] == "cancelled":
            raise AuthError("session_cancelled", "授权已取消", 409)
        if not self.vault.available:
            raise AuthError("vault_unavailable", "服务端未配置凭据密钥，无法保存平台凭据", 503)
        jar = parse_cookie_text(cookie_text)

        platform = s["platform"]
        if platform == "bilibili" and "SESSDATA" not in jar:
            raise AuthError("missing_cookie", "B 站 Cookie 里没有 SESSDATA，请重新登录后再复制")
        if platform == "douyin" and not ({"sessionid", "sessionid_ss", "ttwid"} & set(jar)):
            raise AuthError("missing_cookie", "抖音 Cookie 里没有 sessionid/ttwid，请重新登录后再复制")

        blob = self.vault.seal("; ".join(f"{k}={v}" for k, v in jar.items()))
        now = self.now()
        with self.engine.begin() as c:
            c.execute(text(
                "INSERT INTO platform_credentials(user_id, platform, cookie_blob, status, label, created_at, updated_at)"
                " VALUES(:u,:p,:b,'active',:l,:n,:n)"
                " ON CONFLICT(user_id,platform) DO UPDATE SET cookie_blob=excluded.cookie_blob,"
                " status='active', updated_at=excluded.updated_at"),
                {"u": user_id, "p": platform, "b": blob, "l": f"{len(jar)} 个 Cookie", "n": now})
            c.execute(text(
                "INSERT INTO account_platform_bindings(user_id, platform, bound_at, source, status)"
                " VALUES(:u,:p,:n,:src,'active')"
                " ON CONFLICT(user_id,platform) DO UPDATE SET bound_at=excluded.bound_at,"
                " source=excluded.source, status='active'"),
                {"u": user_id, "p": platform, "n": now, "src": s["method"]})
            c.execute(text("UPDATE platform_auth_sessions SET status='done' WHERE id=:i"), {"i": sid})
        self._write_cookie_file(platform, jar, user_id)
        return {"session_id": sid, "status": "done", "platform": platform, "bound": True,
                "cookie_count": len(jar)}

    def unbind(self, user_id: str, platform: str) -> dict:
        if platform not in PLATFORMS:
            raise AuthError("unknown_platform", f"不支持的平台：{platform}")
        with self.engine.begin() as c:
            n = c.execute(text("DELETE FROM account_platform_bindings WHERE user_id=:u AND platform=:p"),
                          {"u": user_id, "p": platform}).rowcount
            c.execute(text("DELETE FROM platform_credentials WHERE user_id=:u AND platform=:p"),
                      {"u": user_id, "p": platform})
        if not n:
            raise AuthError("not_bound", "该平台尚未绑定", 404)
        # 只删这个用户自己的 cookie 文件，不动运维放的全局 <platform>.txt
        path = Path(self.s.creator_cookie_dir) / f"{platform}.{user_id}.txt"
        try:
            path.unlink(missing_ok=True)
        except OSError:
            log.warning("删除 Cookie 文件失败：%s", platform)
        return {"platform": platform, "unbound": True}

    # ---------- 凭据文件 ----------
    def _write_cookie_file(self, platform: str, jar: dict[str, str], user_id: str) -> None:
        """给 ``creators/`` 用的 Netscape 文件：目录 700、文件 600，先写临时文件再原子改名。

        按 user_id 落名（``<platform>.<user_id>.txt``），这样每个账号各用各的 Cookie，
        不会互相覆盖；抓取侧优先读自己的文件，没有才回退到运维放的全局 ``<platform>.txt``。
        """
        d = Path(self.s.creator_cookie_dir)
        d.mkdir(parents=True, exist_ok=True)
        d.chmod(0o700)
        final = d / f"{platform}.{user_id}.txt"
        part = final.with_name(final.name + ".part")
        fd = os.open(part, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(netscape(jar, platform))
            f.flush()
            os.fsync(f.fileno())
        part.chmod(0o600)
        part.replace(final)

    def credential_state(self, user_id: str) -> list[dict]:
        """只返回状态与数量，不返回任何 Cookie 内容。"""
        with self.engine.begin() as c:
            rows = c.execute(text("SELECT platform, status, label, updated_at FROM platform_credentials"
                                  " WHERE user_id=:u"), {"u": user_id}).all()
        out = []
        for r in rows:
            m = dict(r._mapping)
            out.append({"platform": m["platform"], "status": m["status"], "label": m["label"],
                        "updated_at": m["updated_at"], "decryptable": self._decryptable(m["platform"], user_id)})
        return out

    def _decryptable(self, platform: str, user_id: str) -> bool:
        with self.engine.begin() as c:
            blob = c.execute(text("SELECT cookie_blob FROM platform_credentials WHERE user_id=:u AND platform=:p"),
                             {"u": user_id, "p": platform}).scalar()
        try:
            self.vault.open(blob)
            return True
        except CredentialError:
            return False


__all__ = ["PlatformAuthService", "AuthError", "PLATFORMS", "parse_cookie_text", "netscape"]
